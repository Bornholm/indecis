# Generates the arm64 (NEON) micro-kernels:
#
#     python3 gen_neon.py > kernel_arm64.s
#
# The Go assembler encodes neither UDOT (ARMv8.2 dotprod) nor FMLA by
# element; both are written as WORD, the instruction in the comment.


def udot(acc, a, b):
    # acc.4S += a.16B . b.16B, unsigned, 4 bytes per 32-bit lane
    w = 0x6E809400 | (b << 16) | (a << 5) | acc
    return "\tWORD $0x%08X // UDOT V%d.4S, V%d.16B, V%d.16B" % (w, acc, a, b)


def fmla_elem(acc, b, a, idx):
    # acc.4S += b.4S * a.S[idx]
    w = 0x4F801000 | ((idx & 1) << 21) | ((a >> 4) << 20) | ((a & 15) << 16) | ((idx >> 1) << 11) | (b << 5) | acc
    return "\tWORD $0x%08X // FMLA V%d.4S, V%d.4S, V%d.S[%d]" % (w, acc, b, a, idx)


out = ['''// Code generated by gen_neon.py; DO NOT EDIT.

#include "textflag.h"

// func microKernelNEON(kb int, ap, bp, tile *float32)
//
// 6x16 tile: V0..V23 accumulate C (row r in V(4r)..V(4r+3)), V24..V27
// carry the 16 values of B at the current depth, V28 and V29 the 6
// values of A, each multiplied in by element. FMLA accumulates in place
// (dst += a·b), in the order of the depths, as the Go kernel does.
TEXT ·microKernelNEON(SB), NOSPLIT, $0-32
	MOVD kb+0(FP), R0
	MOVD ap+8(FP), R1
	MOVD bp+16(FP), R2
	MOVD tile+24(FP), R3
''']
for i in range(24):
    out.append("\tVEOR V%d.B16, V%d.B16, V%d.B16" % (i, i, i))
out.append('''
	CBZ R0, store

loop:
	VLD1.P 64(R2), [V24.S4, V25.S4, V26.S4, V27.S4]
	VLD1.P 16(R1), [V28.S4]
	VLD1.P 8(R1), [V29.S2]''')
for r in range(6):
    for g in range(4):
        out.append(fmla_elem(4 * r + g, 24 + g, 28 + r // 4, r % 4))
out.append('''	SUBS $1, R0, R0
	BNE  loop

store:''')
for r in range(6):
    out.append("\tVST1.P [V%d.S4, V%d.S4, V%d.S4, V%d.S4], 64(R3)" % tuple(range(4 * r, 4 * r + 4)))
out.append("\tRET")


def rows(base):
    # R2..R7 point at the 6 rows of A, R8 = lda.
    s = ["\tMOVD %s, R2" % base]
    for r in range(1, 6):
        s.append("\tADD R8, R%d, R%d" % (r + 1, r + 2))
    return s


def int8_body(sfx):
    # Leaves the integer tile in V0..V23 (row r in V(4r)..V(4r+3)); R9 = ap,
    # R8 = lda, R1 = bp; clobbers R0..R11, V24..V31.
    s = []
    for i in range(24):
        s.append("\tVEOR V%d.B16, V%d.B16, V%d.B16" % (i, i, i))
    s += rows("R9")
    s.append('''	VMOVI $128, V28.B16
	CBZ   R0, done%s

loop%s:
	VLD1.P 64(R1), [V24.B16, V25.B16, V26.B16, V27.B16]
	VLD1R.P 4(R2), [V29.S4]
	VLD1R.P 4(R3), [V30.S4]''' % (sfx, sfx))
    for g in range(4):
        s.append("\tVEOR V28.B16, V%d.B16, V%d.B16" % (24 + g, 24 + g))
    for r in range(6):
        reg = 29 + r % 3
        if r >= 2:
            s.append("\tVLD1R.P 4(R%d), [V%d.S4]" % (r + 2, reg))
        for g in range(4):
            s.append(udot(4 * r + g, reg, 24 + g))
    s.append('''	SUBS $1, R0, R0
	BNE  loop%s

done%s:
	// Row sums of A, 16 bytes then 4 at a time: V24..V29 (ones in V30).''' % (sfx, sfx))
    s += rows("R9")
    for i in range(24, 30):
        s.append("\tVEOR V%d.B16, V%d.B16, V%d.B16" % (i, i, i))
    s.append('''	VMOVI $1, V30.B16
	MOVD  kq+0(FP), R10
	AND   $3, R10, R11
	LSR   $2, R10, R10
	CBZ   R10, quads%s

sums%s:''' % (sfx, sfx))
    for r in range(6):
        s.append("\tVLD1.P 16(R%d), [V31.B16]" % (r + 2))
        s.append(udot(24 + r, 31, 30))
    s.append('''	SUBS $1, R10, R10
	BNE  sums%s

quads%s:
	CBZ R11, fix%s

quad%s:''' % (sfx, sfx, sfx, sfx))
    for r in range(6):
        s.append("\tFMOVS.P 4(R%d), F31" % (r + 2))  # upper lanes zeroed
        s.append(udot(24 + r, 31, 30))
    s.append('''	SUBS $1, R11, R11
	BNE  quad%s

fix%s:''' % (sfx, sfx))
    for r in range(6):
        v = 24 + r
        s.append("\tVADDV V%d.S4, V%d" % (v, v))
        s.append("\tVDUP V%d.S[0], V%d.S4" % (v, v))
        s.append("\tVSHL $7, V%d.S4, V%d.S4" % (v, v))
        for g in range(4):
            s.append("\tVSUB V%d.S4, V%d.S4, V%d.S4" % (v, 4 * r + g, 4 * r + g))
    return s


out.append('''
// func microKernelDot(kq int, ap *uint8, lda int, bp *int8, tile *int32)
//
// 6x16 integer tile with UDOT (unsigned 8-bit dot product, ARMv8.2
// dotprod): V0..V23 accumulate C (row r in V(4r)..V(4r+3)), V24..V27
// carry 16 columns x 4 depths of B, V29..V31 broadcast 4 bytes of an A
// row. UDOT multiplies uint8 by uint8 and A is uint8 but B int8: B is
// shifted to uint8 (b+128, an exclusive or with 0x80, V28), then
//
//	sum a·b = sum a·(b+128) - 128·sum a
//
// the row sums of A taken in a second pass. The integers are exact, the
// same as microKernel8Go's.
TEXT ·microKernelDot(SB), NOSPLIT, $0-40
	MOVD kq+0(FP), R0
	MOVD ap+8(FP), R9
	MOVD lda+16(FP), R8
	MOVD bp+24(FP), R1
	MOVD tile+32(FP), R12
''')
out += int8_body("")
out.append("")
for r in range(6):
    out.append("\tVST1.P [V%d.S4, V%d.S4, V%d.S4, V%d.S4], 64(R12)" % tuple(range(4 * r, 4 * r + 4)))
out.append("\tRET")

# The same product, its tile rescaled and stored as float32 in C (see
# MatMul8): c[r][j] (+)= sa[r]·sb[j]·(acc - zc[j]), for a whole 6x16 tile,
# in the order of Dequantize.
out.append('''
// func microKernelDotDeq(kq int, ap *uint8, lda int, bp *int8, c *float32, ldc int, sb, zc, sa *float32, accumulate int)
//
// microKernelDot, its tile then converted in registers: rows of C ldc
// floats apart, sb and zc 16 columns, sa 6 rows; with accumulate != 0, C
// is added to.
TEXT ·microKernelDotDeq(SB), NOSPLIT, $0-80
	MOVD kq+0(FP), R0
	MOVD ap+8(FP), R9
	MOVD lda+16(FP), R8
	MOVD bp+24(FP), R1
''')
out += int8_body("d")
out.append('''
	MOVD zc+56(FP), R12
	VLD1 (R12), [V28.S4, V29.S4, V30.S4, V31.S4]''')
for i in range(24):
    out.append("\tVSCVTF V%d.S4, V%d.S4" % (i, i))
    out.append("\tVFSUB V%d.S4, V%d.S4, V%d.S4" % (28 + i % 4, i, i))
out.append('''	MOVD sb+48(FP), R12
	VLD1 (R12), [V24.S4, V25.S4, V26.S4, V27.S4]''')
for i in range(24):
    out.append("\tVFMUL V%d.S4, V%d.S4, V%d.S4" % (24 + i % 4, i, i))
out.append('''	MOVD sa+64(FP), R12
	VLD1.P 16(R12), [V28.S4]
	VLD1 (R12), [V29.S2]''')
for r in range(6):
    out.append("\tVDUP V%d.S[%d], V30.S4" % (28 + r // 4, r % 4))
    for g in range(4):
        out.append("\tVFMUL V30.S4, V%d.S4, V%d.S4" % (4 * r + g, 4 * r + g))
out.append('''	MOVD c+32(FP), R12
	MOVD ldc+40(FP), R13
	LSL  $2, R13, R13
	MOVD accumulate+72(FP), R14
	CBZ  R14, put''')
for r in range(6):
    out.append("\tVLD1 (R12), [V24.S4, V25.S4, V26.S4, V27.S4]")
    for g in range(4):
        out.append("\tVFADD V%d.S4, V%d.S4, V%d.S4" % (24 + g, 4 * r + g, 4 * r + g))
    out.append("\tVST1.P [V%d.S4, V%d.S4, V%d.S4, V%d.S4], (R12)(R13)" % tuple(range(4 * r, 4 * r + 4)))
out.append("\tRET\n\nput:")
for r in range(6):
    out.append("\tVST1.P [V%d.S4, V%d.S4, V%d.S4, V%d.S4], (R12)(R13)" % tuple(range(4 * r, 4 * r + 4)))
out.append("\tRET")
print("\n".join(out))
