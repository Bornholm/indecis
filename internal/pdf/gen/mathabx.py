dcl = open(sys.argv[1], "rb").read().decode("latin-1").replace("\r", "\n")
dcl = "\n".join(l for l in dcl.split("\n") if not l.lstrip().startswith("%"))
slots = {"matha": {}, "mathb": {}, "mathx": {}}
pat = re.compile(r'\\Declare(?:MathSymbol|MathDelimiter|MathAccent|MathRadical)\{([^}]*)\}\s*\{[^}]*\}'
                 r'\{(matha|mathb|mathx)\}\{"([0-9A-Fa-f]{2})\}(?:\{(matha|mathb|mathx)\}\{"([0-9A-Fa-f]{2})\})?')
for m in pat.finditer(dcl):
    text = TEXT.get(m[1].strip())
    if text is None:
        continue
    for font, slot in ((m[2], m[3]), (m[4], m[5])):
        if font:
            slots[font].setdefault(int(slot, 16), text)

