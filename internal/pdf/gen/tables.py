"""Writes internal/pdf/tables.go: the Adobe Glyph List (BSD-3-Clause, from
fontTools.agl), the standard encodings and the widths of the 14 standard
fonts (Adobe's Core14 AFM files, free to use and distribute).

    python internal/pdf/gen/tables.py AFM_DIR > internal/pdf/tables.go

AFM_DIR holds the Core14 AFM files (pdfcpu ships them in
internal/corefont/Core14_AFMs). Needs fontTools.
"""

import os
import sys
import unicodedata

from fontTools import agl

afm_dir = sys.argv[1]


def afm(name):
    chars, info = [], {}
    for line in open(os.path.join(afm_dir, name + ".afm"), encoding="latin-1"):
        if line.startswith("C "):
            f = dict(p.strip().split(" ", 1) for p in line.split(";") if p.strip())
            chars.append((int(f["C"]), f["N"], int(float(f["WX"]))))
        else:
            k, _, v = line.partition(" ")
            info[k] = v.strip()
    return chars, info


def go_str(s):
    out = []
    for c in s:
        if c == "\\" or c == '"':
            out.append("\\" + c)
        elif c == "\n":
            out.append("\\n")
        elif not c.isprintable() or unicodedata.category(c) in ("Cf", "Co", "Cs"):
            out.append(f"\\u{ord(c):04x}" if ord(c) < 0x10000 else f"\\U{ord(c):08x}")
        else:
            out.append(c)
    return '"' + "".join(out) + '"'


def enc_from_unicode(codec):
    names = [""] * 256
    for c in range(32, 256):
        try:
            u = bytes([c]).decode(codec)
        except UnicodeDecodeError:
            continue
        n = agl.UV2AGL.get(ord(u))
        if n:
            names[c] = n
    return names


std = [""] * 256
for c, n, _ in afm("Helvetica")[0]:
    if c >= 0:
        std[c] = n
sym = [""] * 256
for c, n, _ in afm("Symbol")[0]:
    if c >= 0:
        sym[c] = n
zapf = [""] * 256
for c, n, _ in afm("ZapfDingbats")[0]:
    if c >= 0:
        zapf[c] = n
win = enc_from_unicode("cp1252")
win[39], win[96] = "quotesingle", "grave"
for c in (127, 129, 141, 143, 144, 157):
    win[c] = "bullet"
win[160] = "space"
win[173] = "hyphen"
mac = enc_from_unicode("mac_roman")
mac[219] = "currency"

out = ["// Code generated by gen/tables.py from the Adobe Glyph List and the Core14 AFM files; DO NOT EDIT.", "", "package pdf", ""]
lines = []
for n, uv in sorted(agl.LEGACY_AGL2UV.items()):
    lines.append(n + " " + "".join(chr(u) for u in (uv if isinstance(uv, list) else [uv])))
# The Adobe Glyph List for New Fonts adds names the legacy list lacks.
for n, u in sorted(agl.AGL2UV.items()):
    if n not in agl.LEGACY_AGL2UV:
        lines.append(n + " " + chr(u))
out.append("const glyphList = " + go_str("\n".join(lines)))
out.append("")
for var, names in (("standardEncoding", std), ("winAnsiEncoding", win), ("macRomanEncoding", mac), ("symbolEncoding", sym), ("zapfEncoding", zapf)):
    out.append(f"var {var} = [256]string{{")
    for c, n in enumerate(names):
        if n:
            out.append(f"\t{c}: {go_str(n)},")
    out.append("}")
    out.append("")
out.append("// coreFonts holds the widths of the standard fonts' glyphs by name, and")
out.append("// their ascent and descent, in thousandths of an em.")
out.append("var coreFonts = map[string]coreFont{")
for name in ("Courier", "Courier-Bold", "Courier-Oblique", "Courier-BoldOblique", "Helvetica", "Helvetica-Bold",
             "Helvetica-Oblique", "Helvetica-BoldOblique", "Times-Roman", "Times-Bold", "Times-Italic",
             "Times-BoldItalic", "Symbol", "ZapfDingbats"):
    chars, info = afm(name)
    asc = int(float(info.get("Ascender", info["FontBBox"].split()[3])))
    desc = int(float(info.get("Descender", info["FontBBox"].split()[1])))
    ws = " ".join(f"{n} {w}" for _, n, w in chars)
    out.append(f"\t{go_str(name)}: {{ascent: {asc}, descent: {desc}, widths: {go_str(ws)}}},")
out.append("}")
print("\n".join(out))
