	BYTE $0xC4; BYTE $0x42; BYTE $0x05; BYTE $0x50; BYTE $0xDD // VPDPBUSD Y13, Y15, Y11
	ADDQ $4, SI
	ADDQ $4, R9
	ADDQ $64, DI
